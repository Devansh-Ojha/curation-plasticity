"""Replay saved baseline, ceiling, and A3 telemetry into local Phoenix."""
from __future__ import annotations

import argparse
import json
import re
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional
from zoneinfo import ZoneInfo

from src.obs.phoenix_setup import flush_phoenix, init_phoenix_tracer
from src.obs.spans import span

ROOT = Path(".")
RUN_RE = re.compile(r"(\d{8}T\d{6})")
SOURCE_TIMEZONE = ZoneInfo("America/Los_Angeles")
ARMS = {"baseline": "replay-baseline", "ceiling": "replay-ceiling", "a3": "replay-a3smoke"}
def infer_a3_phase(call: Dict[str, Any]) -> str:
    """Classify legacy A3 calls that predate explicit phase tags.

    Prompt text is inspected in memory only and is never attached to telemetry.
    """
    explicit = call.get("phase")
    if explicit and explicit not in {"unknown", "unassigned"}:
        return str(explicit)
    try:
        messages = json.loads(call.get("prompt_used") or "[]")
    except (json.JSONDecodeError, TypeError):
        messages = []
    system = " ".join(str(m.get("content", "")) for m in messages
                      if isinstance(m, dict) and m.get("role") == "system").lower()
    user_text = " ".join(str(m.get("content", "")) for m in messages
                         if isinstance(m, dict) and m.get("role") == "user").lower()
    if "diagnostic curator" in system or "curator" in system:
        return "curate"
    if ("reflector" in system or "trace bundle" in user_text
            or ("optimizer" in system and "playbook" in system)):
        return "reflect"
    if "gate re-run" in system or "gate evaluation" in user_text or "gate rerun" in user_text:
        return "gate"
    if "held-out evaluation" in user_text or "heldout evaluation" in user_text:
        return "eval"
    # Older smoke call records omitted phase on actor requests. Those were
    # actor episodes; the only non-actor requests are identified above.
    return "act"


def run_start_ns(path: Path) -> Optional[int]:
    match = RUN_RE.search(path.name)
    if not match:
        return None
    # Run IDs are generated by local `date`/`strftime` in America/Los_Angeles.
    dt = datetime.strptime(match.group(1), "%Y%m%dT%H%M%S").replace(tzinfo=SOURCE_TIMEZONE)
    return int(dt.timestamp() * 1_000_000_000)


def jsonl(path: Path) -> List[Dict[str, Any]]:
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            try:
                rows.append(json.loads(line))
            except json.JSONDecodeError:
                continue
    return rows


def _call_rows(path: Path) -> Iterable[Dict[str, Any]]:
    for row in jsonl(path):
        if row.get("event") == "call":
            yield row


def _episodes_for(run_id: str, arm: str) -> List[Dict[str, Any]]:
    if arm == "a3":
        p = Path("outputs/a3") / f"episodes-{run_id}.jsonl"
        if not p.exists():
            return []
        normalized = []
        for row in jsonl(p):
            result = row.get("run_result", {})
            normalized.append({
                "task_id": row.get("task_id"), "epoch": row.get("epoch"),
                "phase": "eval" if str(row.get("cache_key", "")).startswith("eval:") else "act",
                "passed": row.get("passed"), "tokens": result.get("tokens", {}),
                "steps_used": result.get("steps_used", 0),
                "playbook_read": result.get("read_playbook_called", False),
                "trajectory": result.get("trajectory", []),
            })
        return normalized
    out: List[Dict[str, Any]] = []
    for path in sorted(Path(f"outputs/{arm}").glob(f"{'baseline' if arm == 'baseline' else 'ceiling'}-{run_id}.json")):
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (json.JSONDecodeError, OSError):
            continue
        if arm == "baseline":
            for model_id, model_rows in data.get("results", {}).items():
                if not isinstance(model_rows, dict):
                    continue
                for row in model_rows.get("episodes", []):
                    # Category/feedback/answer fields are deliberately discarded.
                    out.append({"task_id": row.get("task_id"), "model_id": model_id,
                                "passed": row.get("passed"), "steps_used": row.get("steps_used", 0),
                                "playbook_read": row.get("read_playbook_called", False),
                                "tokens": row.get("tokens", {}), "trajectory": row.get("trajectory", [])})
        else:
            for row in data.get("episodes", []):
                out.append({"task_id": row.get("task_id"), "passed": row.get("passed"),
                            "steps_used": row.get("steps_used", 0),
                            "playbook_read": row.get("read_playbook_called", False),
                            "tokens": row.get("tokens", {}), "trajectory": row.get("trajectory", [])})
    return out


def replay() -> Dict[str, Any]:
    init_phoenix_tracer(force=True)
    summary: Dict[str, Any] = {arm: {"traces": 0, "spans_per_phase": defaultdict(int),
                                    "input_tokens": 0, "output_tokens": 0,
                                    "reasoning_tokens": 0, "hypothetical_cost_usd": 0.0}
                               for arm in ARMS.values()}
    call_files = sorted(Path("logs").glob("*/calls-*.jsonl"))
    for path in call_files:
        folder = path.parent.name
        if folder not in ARMS:
            continue
        arm_tag = ARMS[folder]
        run_id_match = RUN_RE.search(path.name)
        run_id = run_id_match.group(1) if run_id_match else "unknown"
        run_ns = run_start_ns(path)
        calls = list(_call_rows(path))
        episodes = _episodes_for(run_id, folder)
        result_files = (sorted(Path(f"outputs/{folder}").glob(f"{'smoke_results' if folder == 'a3' else 'baseline' if folder == 'baseline' else 'ceiling'}-{run_id}.json")))
        totals = summary[arm_tag]
        totals["traces"] += 1
        timestamp_source = "run_filename_plus_reported_latency_duration" if run_ns is not None else "replay_time"
        run_end_ns = (run_ns + 1_000_000_000 + sum(
            int(max(0.0, float(row.get("latency_sec") or 0.0)) * 1_000_000_000) for row in calls
        )) if run_ns is not None else None
        with span(f"replay_run__{folder}__{run_id}", phase="replay_run", attributes={
            "arm": arm_tag, "execution_mode": "real", "timestamp_source": timestamp_source,
        }, start_time_ns=run_ns, end_time_ns=run_end_ns):
            for result_path in result_files:
                try:
                    result_data = json.loads(result_path.read_text(encoding="utf-8"))
                except (OSError, json.JSONDecodeError):
                    continue
                phase_costs = result_data.get("phase_costs_hypothetical", {})
                for phase_name, phase_cost in phase_costs.items():
                    with span("replayed_phase_summary", phase=str(phase_name), attributes={
                        "arm": arm_tag, "seed": result_data.get("seed"),
                        "hypothetical_cost_usd": phase_cost,
                        "execution_mode": "real", "timestamp_source": timestamp_source,
                    }, start_time_ns=run_ns,
                       end_time_ns=(run_ns + 1_000_000 if run_ns is not None else None)):
                        pass
                    totals["spans_per_phase"][str(phase_name)] += 1
                if folder == "a3":
                    optimizer_id = result_data.get("optimizer_model")
                    for decision in result_data.get("curator_samples", []):
                        with span("replayed_curator_decision", phase="curate", attributes={
                            "arm": arm_tag, "seed": result_data.get("seed"),
                            "epoch": decision.get("epoch"), "task_id": decision.get("task_id"),
                            "model_id": optimizer_id, "execution_mode": "real",
                            "timestamp_source": timestamp_source,
                        }, start_time_ns=run_ns,
                           end_time_ns=(run_ns + 1_000_000 if run_ns is not None else None)):
                            pass
                        totals["spans_per_phase"]["curator_decision"] += 1
                    for reflection in result_data.get("reflector_samples", []):
                        with span("replayed_reflector_call", phase="reflect", attributes={
                            "arm": arm_tag, "seed": result_data.get("seed"),
                            "epoch": reflection.get("epoch"), "model_id": optimizer_id,
                            "finish_reason": reflection.get("finish_reason"),
                            "execution_mode": "real", "timestamp_source": timestamp_source,
                        }, start_time_ns=run_ns,
                           end_time_ns=(run_ns + 1_000_000 if run_ns is not None else None)):
                            pass
                        totals["spans_per_phase"]["reflector_call"] += 1
                    for attempt in result_data.get("rejected_reflector_attempts", []):
                        if attempt.get("rejection_kind") == "gate":
                            with span("replayed_gate_rerun", phase="gate", attributes={
                                "arm": arm_tag, "seed": result_data.get("seed"),
                                "epoch": attempt.get("epoch"), "model_id": optimizer_id,
                                "execution_mode": "real", "timestamp_source": timestamp_source,
                            }, start_time_ns=run_ns,
                               end_time_ns=(run_ns + 1_000_000 if run_ns is not None else None)):
                                pass
                            totals["spans_per_phase"]["gate_rerun"] += 1
            for call in calls:
                phase = (infer_a3_phase(call) if folder == "a3"
                         else str(call.get("phase") or "act"))
                duration_ns = int(max(0.0, float(call.get("latency_sec") or 0.0)) * 1_000_000_000)
                attrs = {
                    "arm": arm_tag, "phase": phase, "model_id": call.get("model_id"),
                    "request_id": call.get("request_id"), "input_tokens": call.get("input_tokens"),
                    "output_tokens": call.get("output_tokens"), "reasoning_tokens": call.get("reasoning_tokens"),
                    "finish_reason": call.get("finish_reason"),
                    "hypothetical_cost_usd": call.get("hypothetical_cost_usd"),
                    "execution_mode": call.get("execution_mode", "real"),
                    "timestamp_source": timestamp_source,
                }
                with span("replayed_llm_call", phase=phase, attributes=attrs,
                          start_time_ns=run_ns,
                          end_time_ns=(run_ns + duration_ns if run_ns is not None else None)):
                    pass
                totals["spans_per_phase"][phase] += 1
                for key in ("input_tokens", "output_tokens", "reasoning_tokens"):
                    totals[key] += int(call.get(key) or 0)
                totals["hypothetical_cost_usd"] += float(call.get("hypothetical_cost_usd") or 0.0)

            for episode in episodes:
                task_id = episode.get("task_id")
                model_id = episode.get("model_id")
                episode_tokens = episode.get("tokens") or {}
                phase = episode.get("phase", "act")
                eval_context = span("heldout_eval", phase="eval", attributes={
                    "arm": arm_tag, "seed": 42 if folder == "a3" else None,
                    "epoch": episode.get("epoch"), "task_id": task_id,
                    "model_id": model_id, "execution_mode": "real",
                    "timestamp_source": timestamp_source,
                }, start_time_ns=run_ns,
                   end_time_ns=(run_ns + 1_000_000 if run_ns is not None else None)) if phase == "eval" else None
                if eval_context:
                    eval_context.__enter__()
                try:
                    with span("replayed_actor_episode", phase=phase, attributes={
                        "arm": arm_tag, "task_id": task_id, "model_id": model_id,
                        "seed": 42 if folder == "a3" else None,
                        "epoch": episode.get("epoch"), "steps_used": episode.get("steps_used"),
                        "playbook_read": episode.get("playbook_read", episode.get("read_playbook_called")),
                        "success": episode.get("passed"), "execution_mode": "real",
                        "input_tokens": episode_tokens.get("input_tokens"),
                        "output_tokens": episode_tokens.get("output_tokens"),
                        "timestamp_source": timestamp_source,
                    }, start_time_ns=run_ns,
                        end_time_ns=(run_ns + 1_000_000 if run_ns is not None else None)):
                        for step in episode.get("trajectory", []) or []:
                            if step.get("action") == "http_request":
                                request = step
                                result = request.get("result", {})
                                with span("replayed_tool_call", phase="tool_call", attributes={
                                    "arm": arm_tag, "task_id": task_id,
                                    "tool_name": "http_request", "http_method": request.get("method"),
                                    "http_path": request.get("path"),
                                    "http_status": result.get("status") if isinstance(result, dict) else None,
                                    "execution_mode": "real", "timestamp_source": timestamp_source,
                                }, start_time_ns=run_ns,
                                   end_time_ns=(run_ns + 1_000_000 if run_ns is not None else None)):
                                    pass
                                totals["spans_per_phase"]["tool_call"] += 1
                    totals["spans_per_phase"]["act_episode"] += 1
                    if phase == "eval":
                        totals["spans_per_phase"]["eval"] += 1
                finally:
                    if eval_context:
                        eval_context.__exit__(None, None, None)

    flush_phoenix()
    for stats in summary.values():
        stats["spans_per_phase"] = dict(stats["spans_per_phase"])
        stats["total_tokens"] = stats["input_tokens"] + stats["output_tokens"]
        stats["hypothetical_cost_usd"] = round(stats["hypothetical_cost_usd"], 6)
    return summary


def main() -> None:
    parser = argparse.ArgumentParser(description="Replay saved logs into local Phoenix; makes no model calls.")
    parser.parse_args()
    summary = replay()
    print(json.dumps({"project": "curation-plasticity-real", "timestamp_note": (
        "Per-call timestamps are absent from saved logs. Span start_time uses the filename run timestamp "
        "interpreted in America/Los_Angeles "
        "encoded in the filename and recorded latency for duration; exact original per-call timing is unavailable."),
        "summary": summary}, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
